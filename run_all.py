"""Run the real-data pipeline in a predictable order."""
from pathlib import Path

from ml.config import ROOT, load_config, root_path
from ml.data.build_manifest import main as build_manifest
from ml.data.extract_frames import main as extract_frames
from ml.features.extractor import build_cache
from ml.train import main as train


def require_real_dataset() -> Path:
    """Return the configured FF++ root or fail before creating any data."""
    config = load_config()
    raw_data = root_path(config["paths"]["raw_data"])
    if not raw_data.is_dir():
        raise FileNotFoundError(
            f"Real FaceForensics++ data is required at {raw_data}. "
            "Download it from the official source and place the c23 videos "
            "under data/raw before running the pipeline."
        )
    video_roots = list(raw_data.glob("original_sequences/youtube/c23/videos"))
    video_roots += list(raw_data.glob("manipulated_sequences/*/c23/videos"))
    if not any(path.is_dir() and any(path.glob("*.mp4")) for path in video_roots):
        raise FileNotFoundError(
            f"No real FF++ c23 videos were found under {raw_data}. "
            "Synthetic data is intentionally not generated by this command."
        )
    return raw_data


if __name__ == "__main__":
    require_real_dataset()
    print(f"Real dataset found under {ROOT / 'data' / 'raw'}.")
    extract_frames()
    build_manifest()
    build_cache()
    train()
    print("Real-data ingestion, feature extraction, and training completed.")
